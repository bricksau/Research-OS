#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Word master -> Markdown mirror, so that the checks (and AI assistants) can read the text without opening Word.

    python3 scripts/checks/docx_to_md.py [papers/manuscript/Paper_Master.docx] [-o OUT.md]

Default: every *.docx in papers/manuscript/ (except ~$ lock files) gets a .md of the same name next to it.
The mirror is generated: never edit it, edit the .docx and run this again (check_all.sh does it for you).
Keeps headings (Heading 1-4, Title), body paragraphs, tables (as pipe rows) and footnotes ([^n] in the text, the
notes at the end under "# Footnotes", numbered in order of appearance). Formatting is not kept on purpose.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"


def para_text(p_el, notes_order: dict[str, int]) -> str:
    out = []
    for el in p_el.iter():
        if el.tag == W + "t":
            out.append(el.text or "")
        elif el.tag == W + "tab":
            out.append("\t")
        elif el.tag in (W + "br", W + "cr"):
            out.append(" ")
        elif el.tag == W + "footnoteReference":
            fid = el.get(W + "id")
            notes_order.setdefault(fid, len(notes_order) + 1)
            out.append(f"[^{notes_order[fid]}]")
    return "".join(out)


def heading_level(style_name: str) -> int:
    if style_name == "Title":
        return 1
    m = re.match(r"(?:Heading|제목|标题)\s*(\d)", style_name or "")
    return int(m.group(1)) if m else 0


def footnotes(doc) -> dict[str, str]:
    for rel in doc.part.rels.values():
        if rel.reltype.endswith("/footnotes"):
            from lxml import etree
            root = etree.fromstring(rel.target_part.blob)
            out = {}
            for fn in root.findall(W + "footnote"):
                if fn.get(W + "type") in ("separator", "continuationSeparator", "continuationNotice"):
                    continue
                text = " ".join(para_text(p, {}) for p in fn.findall(W + "p")).strip()
                out[fn.get(W + "id")] = re.sub(r"\s+", " ", text)
            return out
    return {}


def convert(src: Path) -> str:
    import docx  # python-docx
    from docx.table import Table
    from docx.text.paragraph import Paragraph

    doc = docx.Document(str(src))
    order: dict[str, int] = {}
    lines: list[str] = []
    for child in doc.element.body.iterchildren():
        if child.tag == W + "p":
            p = Paragraph(child, doc)
            text = para_text(child, order).strip()
            if not text:
                continue
            lev = heading_level(p.style.name if p.style is not None else "")
            lines.append(("#" * lev + " " + text) if lev else text)
            lines.append("")
        elif child.tag == W + "tbl":
            t = Table(child, doc)
            for k, row in enumerate(t.rows):
                cells = [para_text(c._tc, order).strip().replace("|", "\\|").replace("\n", " ") for c in row.cells]
                lines.append("| " + " | ".join(cells) + " |")
                if k == 0:
                    lines.append("|" + "---|" * len(cells))
            lines.append("")
    notes = footnotes(doc)
    if order:
        lines += ["---", "", "# Footnotes", ""]
        for fid, n in sorted(order.items(), key=lambda kv: kv[1]):
            lines.append(f"[^{n}]: {notes.get(fid, '')}")
    return "<!-- generated by scripts/checks/docx_to_md.py from " + src.name + "; do not edit -->\n\n" + "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("docx", nargs="*")
    ap.add_argument("-o", "--out")
    a = ap.parse_args()
    srcs = [Path(s) for s in a.docx] or sorted(p for p in (ROOT / "papers" / "manuscript").glob("*.docx")
                                               if not p.name.startswith("~$"))
    if not srcs:
        print("no .docx master in papers/manuscript/ (a Markdown master needs no mirror)")
        return 0
    try:
        import docx  # noqa: F401
    except ImportError:
        print("python-docx is missing: pip install python-docx")
        return 1
    for src in srcs:
        out = Path(a.out) if a.out and len(srcs) == 1 else src.with_suffix(".md")
        out.write_text(convert(src), encoding="utf-8")
        print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
